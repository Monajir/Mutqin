import type { NotificationSettings } from '@/stores';

export const REMINDER_PREFIX = 'mutqin.reminder.';
export const TEST_ID = 'mutqin.test';
export const CHANNEL_ID = 'mutqin-reminders';
export const SCHEDULE_DAYS = 3;

export interface Reminder {
  id: string;
  at: number;
  title: string;
  body: string;
  route: string;
}

export interface ReminderDay {
  date: Date;
  prayers: { name: string; time: string }[];
  verse?: { translation: string; reference: string; surahId: number; ayahNumber: number } | null;
  hadith?: { excerpt: string; source: string; collectionId: string; reference: string } | null;
}

export function dateKey(date: Date): string {
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`;
}

export function validTime(value: string): boolean {
  return /^([01]\d|2[0-3]):[0-5]\d$/.test(value);
}

function atTime(date: Date, time: string): number {
  if (!validTime(time)) return NaN;
  const [hour, minute] = time.split(':').map(Number);
  const result = new Date(date);
  result.setHours(hour!, minute!, 0, 0);
  return result.getTime();
}

/** Finite one-off reminders: no perpetual stale prayer times or repeated daily content. */
export function buildReminderPlan(settings: NotificationSettings, days: ReminderDay[], now: number): Reminder[] {
  if (!settings.enabled) return [];
  const result: Reminder[] = [];
  for (const day of days) {
    const key = dateKey(day.date);
    const add = (kind: string, at: number, title: string, body: string, route: string) => {
      if (Number.isFinite(at) && at > now) result.push({
        id: `${REMINDER_PREFIX}${key}.${kind}`, at, title, body, route,
      });
    };
    for (const prayer of day.prayers) {
      if (settings.prayerReminders && prayer.name !== 'Sunrise') {
        add(prayer.name, Date.parse(prayer.time), `Time for ${prayer.name}`, 'Open Mutqin to view prayer times.', '/(tabs)/prayer');
      }
      if (settings.morningAdhkar && prayer.name === 'Fajr') {
        add('morning', Date.parse(prayer.time) + settings.morningOffsetMinutes * 60000,
          'Morning Adhkar', 'Take a moment for your morning remembrance.', '/(tabs)/more/duas?category=morning-adhkar');
      }
      if (settings.eveningAdhkar && prayer.name === 'Asr') {
        add('evening', Date.parse(prayer.time) + settings.eveningOffsetMinutes * 60000,
          'Evening Adhkar', 'Take a moment for your evening remembrance.', '/(tabs)/more/duas?category=evening-adhkar');
      }
    }
    if (settings.dailyVerse && day.verse) {
      const verse = day.verse;
      add('verse', atTime(day.date, settings.dailyVerseTime), `Daily verse · ${verse.reference}`, verse.translation,
        `/(tabs)/quran/${verse.surahId}?ayah=${verse.ayahNumber}`);
    }
    if (settings.dailyHadith && day.hadith) {
      const hadith = day.hadith;
      add('hadith', atTime(day.date, settings.dailyHadithTime), `Daily hadith · ${hadith.source}`, hadith.excerpt,
        `/(tabs)/more/hadith/${encodeURIComponent(hadith.collectionId)}?reference=${encodeURIComponent(hadith.reference)}`);
    }
    if (settings.fridayReminder && day.date.getDay() === 5) {
      add('friday', atTime(day.date, settings.fridayTime), 'Friday reminder', 'Make time to read Surah Al-Kahf today.', '/(tabs)/quran/18?ayah=1');
    }
  }
  return result.sort((a, b) => a.at - b.at);
}

/** Accept only destinations generated by this app, never arbitrary notification URLs. */
export function safeReminderRoute(route: unknown): string | null {
  if (typeof route !== 'string') return null;
  if (route === '/settings/notifications' || route === '/(tabs)/prayer') return route;
  if (/^\/\(tabs\)\/more\/duas\?category=(morning|evening)-adhkar$/.test(route)) return route;
  const quran = route.match(/^\/\(tabs\)\/quran\/(\d+)\?ayah=(\d+)$/);
  if (quran && Number(quran[1]) >= 1 && Number(quran[1]) <= 114 && Number(quran[2]) >= 1 && Number(quran[2]) <= 286) return route;
  if (/^\/\(tabs\)\/more\/hadith\/[a-zA-Z0-9_-]+\?reference=[^&?#]+$/.test(route)) return route;
  return null;
}
